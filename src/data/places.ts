type Spec = Partial<Record<string, [ItemStatus, string?, string?]>>

function ficha(placeId: string, spec: Spec): FichaItem[] {
  return FICHA_ATTRS.map((a) => {
    const [status, valor, observacao] = spec[a.key] ?? ['nao_informado']
    return {
      id: `${placeId}-${a.key}`,
      categoria: a.categoria,
      atributo: a.atributo,
      curto: a.curto,
      necessidades: a.necessidades,
      status,
      valor,
      observacao,
    }
  })
}

